import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { ALL_LOCALE_CODES } from "../src/i18n/locales.js";
import { analyzeIcuMessage } from "./validate-locales.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const flatten = (value, prefix = "") =>
  Object.fromEntries(
    Object.entries(value || {}).flatMap(([key, child]) => {
      const name = prefix ? `${prefix}.${key}` : key;
      return typeof child === "string"
        ? [[name, child]]
        : Object.entries(flatten(child, name));
    }),
  );
const output = process.argv[2];
if (!output || !path.isAbsolute(output)) {
  throw new Error(
    "Pass an absolute output path in the separate Shario server repository.",
  );
}
const catalogs = Object.fromEntries(
  ALL_LOCALE_CODES.map((locale) => [
    locale,
    flatten(
      JSON.parse(
        fs.readFileSync(path.join(root, `src/messages/${locale}.json`), "utf8"),
      ).AIProduct,
    ),
  ]),
);
const keys = Object.keys(catalogs.en).sort();
if (!keys.length) throw new Error("The English AI product catalog is empty.");
for (const [locale, catalog] of Object.entries(catalogs)) {
  if (JSON.stringify(Object.keys(catalog).sort()) !== JSON.stringify(keys)) {
    throw new Error(`${locale}: AI product catalog is incomplete.`);
  }
  for (const key of keys) {
    if (!catalog[key].trim()) throw new Error(`${locale}: empty ${key}`);
    if (
      JSON.stringify(analyzeIcuMessage(catalog[key]).argumentSignatures) !==
      JSON.stringify(analyzeIcuMessage(catalogs.en[key]).argumentSignatures)
    ) {
      throw new Error(`${locale}: incompatible ICU arguments for ${key}`);
    }
  }
}
const source = `// Generated by shario-client/scripts/export-ai-product-catalogs.mjs.\n// Edit AIProduct in the Shario catalogs and export again.\nimport type { AiLocale } from "./ai-locale.js";\n\nexport const AI_PRODUCT_MESSAGES: Record<AiLocale, Record<string, string>> = ${JSON.stringify(catalogs, null, 2)};\n`;
fs.writeFileSync(output, source);
console.log(
  `Exported ${keys.length} AI product messages in ${ALL_LOCALE_CODES.length} languages.`,
);
